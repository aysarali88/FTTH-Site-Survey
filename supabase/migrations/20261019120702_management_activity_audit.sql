create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists public.management_activity (
  id bigint generated by default as identity primary key,
  action text not null,
  source text not null default 'trigger' check (source in ('trigger', 'baseline')),
  entity_type text not null,
  entity_id text,
  batch_id text,
  actor_user_id uuid,
  actor_username text,
  actor_name text,
  actor_role text,
  target_username text,
  city text,
  district text,
  summary text not null,
  details jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists management_activity_occurred_at_idx
  on public.management_activity (occurred_at desc, id desc);
create index if not exists management_activity_batch_id_idx
  on public.management_activity (batch_id) where batch_id is not null;
create index if not exists management_activity_action_idx
  on public.management_activity (action, occurred_at desc);
create unique index if not exists management_activity_batch_event_idx
  on public.management_activity (action, batch_id)
  where action in ('design_batch_uploaded', 'design_batch_deleted') and batch_id is not null;

alter table public.management_activity enable row level security;

drop policy if exists "admin and management read activity" on public.management_activity;
create policy "admin and management read activity" on public.management_activity
for select to authenticated using (public.current_app_role() in ('admin', 'management'));

revoke all on public.management_activity from anon, authenticated;
grant select on public.management_activity to authenticated;

create or replace function private.record_management_activity(
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_batch_id text,
  p_actor_user_id uuid,
  p_actor_username text,
  p_actor_name text,
  p_actor_role text,
  p_target_username text,
  p_city text,
  p_district text,
  p_summary text,
  p_details jsonb default '{}'::jsonb,
  p_source text default 'trigger',
  p_occurred_at timestamptz default now()
)
returns void
language sql
security definer
set search_path = pg_catalog
as $$
  insert into public.management_activity (
    action, source, entity_type, entity_id, batch_id,
    actor_user_id, actor_username, actor_name, actor_role, target_username,
    city, district, summary, details, occurred_at
  ) values (
    p_action, p_source, p_entity_type, p_entity_id, p_batch_id,
    p_actor_user_id, p_actor_username, p_actor_name, p_actor_role, p_target_username,
    p_city, p_district, p_summary, coalesce(p_details, '{}'::jsonb), p_occurred_at
  )
  on conflict do nothing;
$$;

revoke all on function private.record_management_activity(
  text, text, text, text, uuid, text, text, text, text, text, text, text, jsonb, text, timestamptz
) from public, anon, authenticated;

create or replace function private.capture_management_activity()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_actor_id uuid;
  v_actor_username text;
  v_actor_name text;
  v_actor_role text;
  v_actor_source text;
  v_action text;
  v_summary text;
  v_entity_id text;
  v_batch_id text;
  v_city text;
  v_district text;
begin
  if tg_op = 'DELETE' then
    v_entity_id := old.id;
    v_city := old.city;
    v_district := old.district;
    if tg_table_name <> 'column_checks' then v_batch_id := old.batch_id; end if;
  else
    v_entity_id := new.id;
    v_city := new.city;
    v_district := new.district;
    if tg_table_name <> 'column_checks' then v_batch_id := new.batch_id; end if;
  end if;

  if tg_table_name = 'column_checks' then
    v_actor_source := case when tg_op = 'DELETE' then old.tech_name else new.tech_name end;
  elsif tg_op = 'UPDATE' then
    v_actor_source := coalesce(new.validated_by, new.created_by);
  else
    v_actor_source := case when tg_op = 'DELETE' then old.created_by else new.created_by end;
  end if;

  v_actor_id := auth.uid();
  if v_actor_id is not null then
    select username, coalesce(display_name, username), role
      into v_actor_username, v_actor_name, v_actor_role
    from public.user_profiles
    where id = v_actor_id;
  end if;

  if v_actor_username is null and v_actor_source is not null then
    select id, username, coalesce(display_name, username), role
      into v_actor_id, v_actor_username, v_actor_name, v_actor_role
    from public.user_profiles
    where username = v_actor_source
    limit 1;
  end if;

  v_actor_username := coalesce(v_actor_username, v_actor_source);
  v_actor_name := coalesce(v_actor_name, v_actor_username, 'Unknown user');

  if tg_table_name in ('planned_routes', 'planned_assets') then
    if tg_op = 'INSERT' and v_batch_id is not null then
      perform private.record_management_activity(
        'design_batch_uploaded', 'batch', v_batch_id, v_batch_id,
        v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'design'), null,
        v_city, v_district,
        format('Design area uploaded for %s / %s', coalesce(v_city, '-'), coalesce(v_district, '-')),
        jsonb_build_object('upload_source_table', tg_table_name)
      );
    elsif tg_op = 'DELETE' and v_batch_id is not null then
      perform private.record_management_activity(
        'design_batch_deleted', 'batch', v_batch_id, v_batch_id,
        v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'design'), null,
        v_city, v_district,
        format('Uploaded design area deleted for %s / %s', coalesce(v_city, '-'), coalesce(v_district, '-')),
        jsonb_build_object('delete_source_table', tg_table_name)
      );
    end if;
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  if tg_table_name = 'planned_poles' then
    if tg_op = 'INSERT' then
      if v_batch_id is not null then
        perform private.record_management_activity(
          'design_batch_uploaded', 'batch', v_batch_id, v_batch_id,
          v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'design'), null,
          v_city, v_district,
          format('Design area uploaded for %s / %s', coalesce(v_city, '-'), coalesce(v_district, '-')),
          '{}'::jsonb
        );
      else
        perform private.record_management_activity(
          'engineer_point_added', 'planned_pole', v_entity_id, null,
          v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'engineer'), null,
          v_city, v_district, format('Engineer added point %s', v_entity_id),
          jsonb_build_object('point_name', new.point_name, 'latitude', new.latitude, 'longitude', new.longitude)
        );
      end if;
      return new;
    elsif tg_op = 'DELETE' then
      if v_batch_id is not null then
        perform private.record_management_activity(
          'design_batch_deleted', 'batch', v_batch_id, v_batch_id,
          v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'design'), null,
          v_city, v_district,
          format('Uploaded design area deleted for %s / %s', coalesce(v_city, '-'), coalesce(v_district, '-')),
          '{}'::jsonb
        );
      end if;
      return old;
    end if;

    if old.deleted_at is null and new.deleted_at is not null then
      perform private.record_management_activity(
        'engineer_point_deleted', 'planned_pole', v_entity_id, v_batch_id,
        v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'engineer'), null,
        v_city, v_district, format('Engineer removed point %s from the work queue', v_entity_id),
        jsonb_build_object('point_name', new.point_name)
      );
    end if;

    if old.validation_status is distinct from new.validation_status
      and new.validation_status <> 'planted'
      and not (old.validation_status = 'planted' and new.validation_status = 'validated') then
      v_action := case when new.validation_status = 'rejected' then 'point_rejected' else 'point_validated' end;
      v_summary := case when new.validation_status = 'rejected'
        then format('Engineer rejected point %s', v_entity_id)
        else format('Engineer validated point %s', v_entity_id)
      end;
      perform private.record_management_activity(
        v_action, 'planned_pole', v_entity_id, v_batch_id,
        v_actor_id, coalesce(v_actor_username, new.validated_by), v_actor_name,
        coalesce(v_actor_role, 'engineer'), null, v_city, v_district, v_summary,
        jsonb_build_object('status_before', old.validation_status, 'status_after', new.validation_status, 'notes', new.validation_notes)
      );
    end if;

    if old.assigned_to is distinct from new.assigned_to then
      v_action := case when new.assigned_to is null then 'point_unassigned' else 'point_assigned' end;
      v_summary := case when new.assigned_to is null
        then format('Engineer removed the assignment for point %s', v_entity_id)
        else format('Engineer assigned point %s to %s', v_entity_id, new.assigned_to)
      end;
      perform private.record_management_activity(
        v_action, 'planned_pole', v_entity_id, v_batch_id,
        v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'engineer'), new.assigned_to,
        v_city, v_district, v_summary,
        jsonb_build_object('previous_technician', old.assigned_to, 'technician', new.assigned_to)
      );
    end if;

    if old.latitude is distinct from new.latitude or old.longitude is distinct from new.longitude then
      perform private.record_management_activity(
        'point_location_updated', 'planned_pole', v_entity_id, v_batch_id,
        v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'engineer'), null,
        v_city, v_district, format('Engineer moved point %s', v_entity_id),
        jsonb_build_object(
          'latitude_before', old.latitude, 'longitude_before', old.longitude,
          'latitude_after', new.latitude, 'longitude_after', new.longitude
        )
      );
    end if;
    return new;
  end if;

  if tg_table_name = 'column_checks' then
    if tg_op = 'INSERT' then
      v_action := case when new.is_planted then 'technician_planting_record' else 'technician_field_record' end;
      v_summary := case when new.is_planted
        then format('Technician recorded a planting in %s / %s', coalesce(v_city, '-'), coalesce(v_district, '-'))
        else format('Technician recorded a field check in %s / %s', coalesce(v_city, '-'), coalesce(v_district, '-'))
      end;
      perform private.record_management_activity(
        v_action, 'planting_record', v_entity_id, null,
        v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'tech'), null,
        v_city, v_district, v_summary,
        jsonb_build_object('is_planted', new.is_planted, 'is_existing', new.is_existing, 'has_objection', new.has_objection)
      );
      return new;
    elsif tg_op = 'UPDATE' then
      if row(old.latitude, old.longitude, old.city, old.district, old.tech_name, old.has_objection, old.is_existing, old.is_planted, old.notes, old.photo_url)
        is distinct from row(new.latitude, new.longitude, new.city, new.district, new.tech_name, new.has_objection, new.is_existing, new.is_planted, new.notes, new.photo_url) then
        perform private.record_management_activity(
          'technician_record_updated', 'planting_record', v_entity_id, null,
          v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'tech'), null,
          v_city, v_district, format('Field record %s was updated', v_entity_id),
          jsonb_build_object('is_planted', new.is_planted, 'is_existing', new.is_existing, 'has_objection', new.has_objection)
        );
      end if;
      return new;
    else
      perform private.record_management_activity(
        'technician_record_deleted', 'planting_record', v_entity_id, null,
        v_actor_id, v_actor_username, v_actor_name, coalesce(v_actor_role, 'tech'), null,
        v_city, v_district, format('Field record %s was deleted', v_entity_id),
        jsonb_build_object('is_planted', old.is_planted, 'is_existing', old.is_existing, 'has_objection', old.has_objection)
      );
      return old;
    end if;
  end if;

  return null;
end;
$$;

revoke all on function private.capture_management_activity() from public, anon, authenticated;

drop trigger if exists management_activity_planned_poles on public.planned_poles;
create trigger management_activity_planned_poles
after insert or update or delete on public.planned_poles
for each row execute function private.capture_management_activity();

drop trigger if exists management_activity_planned_routes on public.planned_routes;
create trigger management_activity_planned_routes
after insert or delete on public.planned_routes
for each row execute function private.capture_management_activity();

drop trigger if exists management_activity_planned_assets on public.planned_assets;
create trigger management_activity_planned_assets
after insert or delete on public.planned_assets
for each row execute function private.capture_management_activity();

drop trigger if exists management_activity_column_checks on public.column_checks;
create trigger management_activity_column_checks
after insert or update or delete on public.column_checks
for each row execute function private.capture_management_activity();

with batch_rows as (
  select batch_id, city, district, created_by, created_at, 'pole'::text as kind
  from public.planned_poles where batch_id is not null
  union all
  select batch_id, city, district, created_by, created_at, 'route'::text
  from public.planned_routes where batch_id is not null
  union all
  select batch_id, city, district, created_by, created_at, 'asset'::text
  from public.planned_assets where batch_id is not null
), batches as (
  select batch_id, min(city) as city, min(district) as district, min(created_by) as created_by,
    min(created_at) as occurred_at,
    count(*) filter (where kind = 'pole') as pole_count,
    count(*) filter (where kind = 'route') as route_count,
    count(*) filter (where kind = 'asset') as asset_count
  from batch_rows group by batch_id
)
insert into public.management_activity (
  action, source, entity_type, entity_id, batch_id, actor_username, actor_name, actor_role,
  city, district, summary, details, occurred_at
)
select 'design_batch_uploaded', 'baseline', 'batch', batches.batch_id, batches.batch_id,
  coalesce(profile.username, batches.created_by), coalesce(profile.display_name, profile.username, batches.created_by, 'Unknown user'),
  coalesce(profile.role, 'design'), batches.city, batches.district,
  format('Existing design batch for %s / %s', coalesce(batches.city, '-'), coalesce(batches.district, '-')),
  jsonb_build_object('poles', batches.pole_count, 'routes', batches.route_count, 'features', batches.asset_count, 'historical_snapshot', true),
  batches.occurred_at
from batches
left join public.user_profiles profile on profile.username = batches.created_by
on conflict do nothing;

insert into public.management_activity (
  action, source, entity_type, entity_id, batch_id, actor_username, actor_name, actor_role,
  target_username, city, district, summary, details, occurred_at
)
select case when pole.validation_status = 'rejected' then 'point_rejected' else 'point_validated' end,
  'baseline', 'planned_pole', pole.id, pole.batch_id,
  coalesce(profile.username, pole.validated_by), coalesce(profile.display_name, profile.username, pole.validated_by, 'Historical record'),
  coalesce(profile.role, 'engineer'), pole.assigned_to, pole.city, pole.district,
  case when pole.validation_status = 'rejected' then format('Existing rejected point %s', pole.id) else format('Existing validated point %s', pole.id) end,
  jsonb_build_object('status_after', pole.validation_status, 'historical_snapshot', true, 'actor_unavailable', profile.id is null),
  pole.validated_at
from public.planned_poles pole
left join public.user_profiles profile on profile.username = pole.validated_by
where pole.validated_at is not null and pole.validation_status in ('validated', 'rejected', 'planted');

insert into public.management_activity (
  action, source, entity_type, entity_id, batch_id, actor_name, actor_role,
  target_username, city, district, summary, details, occurred_at
)
select 'point_assigned', 'baseline', 'planned_pole', pole.id, pole.batch_id,
  'Historical record', 'engineer', pole.assigned_to, pole.city, pole.district,
  format('Existing assignment of point %s to %s', pole.id, pole.assigned_to),
  jsonb_build_object('historical_snapshot', true, 'actor_unavailable', true), pole.assigned_at
from public.planned_poles pole
where pole.assigned_to is not null and pole.assigned_at is not null;

insert into public.management_activity (
  action, source, entity_type, entity_id, actor_username, actor_name, actor_role,
  city, district, summary, details, occurred_at
)
select case when check_row.is_planted then 'technician_planting_record' else 'technician_field_record' end,
  'baseline', 'planting_record', check_row.id,
  coalesce(profile.username, check_row.tech_name), coalesce(profile.display_name, profile.username, check_row.tech_name, 'Historical record'),
  coalesce(profile.role, 'tech'), check_row.city, check_row.district,
  case when check_row.is_planted
    then format('Existing planting record in %s / %s', coalesce(check_row.city, '-'), coalesce(check_row.district, '-'))
    else format('Existing field record in %s / %s', coalesce(check_row.city, '-'), coalesce(check_row.district, '-'))
  end,
  jsonb_build_object('is_planted', check_row.is_planted, 'is_existing', check_row.is_existing, 'has_objection', check_row.has_objection, 'historical_snapshot', true),
  check_row.created_at
from public.column_checks check_row
left join public.user_profiles profile on profile.username = check_row.tech_name;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'management_activity'
    ) then
    execute 'alter publication supabase_realtime add table public.management_activity';
  end if;
end;
$$;
